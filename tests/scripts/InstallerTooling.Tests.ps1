Invoke-TestCase 'installer build validates payload files before compiler invocation' {
    foreach ($missingName in @('apollo.exe', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'assets/apollo.ico')) {
        $fixture = New-InstallerFixture
        try {
            $marker = Join-Path $fixture.Root 'compiler-invoked.txt'
            $env:APOLLO_TEST_NSIS_MARKER = $marker

            switch ($missingName) {
                'apollo.exe' { Remove-Item -LiteralPath $fixture.Executable -Force }
                default { Remove-Item -LiteralPath (Join-Path $fixture.Root $missingName) -Force }
            }

            Assert-Throws {
                Invoke-ScriptCapture -ScriptPath $buildInstallerScript -Arguments @(
                    '--project', $fixture.Root,
                    '--makensis', $fixture.Compiler
                ) | Out-Null
            } '*does not exist*'
            Assert-PathMissing $marker "Missing $missingName must fail before the NSIS compiler runs."
        }
        finally {
            Reset-NsisTestEnvironment
            Remove-Item -LiteralPath $fixture.Root -Recurse -Force
        }
    }
}

Invoke-TestCase 'installer build rejects non-GUI or non-x64 payloads before compiler invocation' {
    foreach ($case in @(
        @{ Name = 'console'; Architecture = 'x64'; Subsystem = [uint16]3; Pattern = '*Windows GUI subsystem*' },
        @{ Name = 'x86'; Architecture = 'x86'; Subsystem = [uint16]2; Pattern = '*must target Windows x64*' }
    )) {
        $fixture = New-InstallerFixture
        try {
            $marker = Join-Path $fixture.Root 'compiler-invoked.txt'
            $env:APOLLO_TEST_NSIS_MARKER = $marker
            New-TestWindowsExecutable `
                -Path $fixture.Executable `
                -Architecture $case.Architecture `
                -Subsystem $case.Subsystem | Out-Null

            Assert-Throws {
                Invoke-ScriptCapture -ScriptPath $buildInstallerScript -Arguments @(
                    '--project', $fixture.Root,
                    '--makensis', $fixture.Compiler
                ) | Out-Null
            } $case.Pattern
            Assert-PathMissing $marker "Invalid $($case.Name) payload must fail before NSIS compiler invocation."
        }
        finally {
            Reset-NsisTestEnvironment
            Remove-Item -LiteralPath $fixture.Root -Recurse -Force
        }
    }
}

