$checkReleaseScript = Join-Path $projectRoot 'scripts/check-release.ps1'
$setVersionScript = Join-Path $projectRoot 'scripts/set-version.ps1'

$originalGitHubRefType = $env:GITHUB_REF_TYPE
$originalGitHubRefName = $env:GITHUB_REF_NAME
