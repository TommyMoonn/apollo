function New-ReleaseFixture {
    param(
        [string]$Version = '0.1.0',
        [string]$LockVersion = $Version,
        [switch]$WithReleaseChangelog
    )

    $root = New-TestDirectory -Name 'apollo-release'
    New-Item -ItemType Directory -Path (Join-Path $root 'src') -Force | Out-Null

    $manifest = @"
[package]
name = "apollo"
version = "$Version"
edition = "2024"
"@
    Set-Content -LiteralPath (Join-Path $root 'Cargo.toml') -Value $manifest -Encoding utf8

    $lockfile = @"
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "apollo"
version = "$LockVersion"
"@
    Set-Content -LiteralPath (Join-Path $root 'Cargo.lock') -Value $lockfile -Encoding utf8

    'fn main() {}' | Set-Content -LiteralPath (Join-Path $root 'src/main.rs') -Encoding utf8

    if ($WithReleaseChangelog) {
        $changelog = @"
# Changelog

## [Unreleased]

## [$Version] - 2026-08-22

[$Version]: https://github.com/example/apollo/releases/tag/v$Version
"@
    }
    else {
        $changelog = @"
# Changelog

## [Unreleased]
"@
    }
    Set-Content -LiteralPath (Join-Path $root 'CHANGELOG.md') -Value $changelog -Encoding utf8

    return $root
}

Invoke-TestCase 'release validator accepts full semantic version syntax' {
    $repo = New-ReleaseFixture -Version '1.2.3-rc.1+build.5' -LockVersion '1.2.3-rc.1+build.5'
    try {
        Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--project', $repo) | Out-Null
    }
    finally {
        Remove-Item -LiteralPath $repo -Recurse -Force
    }
}

Invoke-TestCase 'release validator accepts aligned versions without modifying files' {
    $repo = New-ReleaseFixture
    try {
        $manifestBefore = [System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.toml'))
        $lockBefore = [System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.lock'))
        $changelogBefore = [System.IO.File]::ReadAllBytes((Join-Path $repo 'CHANGELOG.md'))

        $output = Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--project', $repo)
        Assert-Contains $output 'Release metadata valid' 'Aligned release metadata should validate.'

        Assert-Equal $manifestBefore ([System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.toml'))) 'Validator must not modify Cargo.toml.'
        Assert-Equal $lockBefore ([System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.lock'))) 'Validator must not modify Cargo.lock.'
        Assert-Equal $changelogBefore ([System.IO.File]::ReadAllBytes((Join-Path $repo 'CHANGELOG.md'))) 'Validator must not modify CHANGELOG.md.'
    }
    finally {
        Remove-Item -LiteralPath $repo -Recurse -Force
    }
}

