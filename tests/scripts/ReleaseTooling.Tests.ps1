Invoke-TestCase 'set-version updates Cargo manifest and lock through Cargo' {
    $repo = New-ReleaseFixture
    try {
        Invoke-ScriptCapture -ScriptPath $setVersionScript -Arguments @('0.2.0', '--project', $repo) | Out-Null

        $manifest = Get-CargoManifestPackageInfo -ManifestPath (Join-Path $repo 'Cargo.toml')
        $lockVersion = Get-CargoLockRootPackageVersion -LockPath (Join-Path $repo 'Cargo.lock') -PackageName 'apollo'
        Assert-Equal '0.2.0' $manifest.Version 'Cargo.toml package version should be updated.'
        Assert-Equal '0.2.0' $lockVersion 'Cargo.lock root package version should be refreshed.'

        Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--project', $repo) | Out-Null
    }
    finally {
        Remove-Item -LiteralPath $repo -Recurse -Force
    }
}

Invoke-TestCase 'set-version rolls back manifest and lock when final validation fails' {
    $repo = New-ReleaseFixture
    $savedType = $env:GITHUB_REF_TYPE
    $savedName = $env:GITHUB_REF_NAME
    $savedRef = $env:GITHUB_REF
    try {
        $manifestBefore = [System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.toml'))
        $lockBefore = [System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.lock'))

        $env:GITHUB_REF_TYPE = 'tag'
        $env:GITHUB_REF_NAME = 'v9.9.9'
        $env:GITHUB_REF = 'refs/tags/v9.9.9'

        Assert-Throws {
            Invoke-ScriptCapture -ScriptPath $setVersionScript -Arguments @('0.2.0', '--project', $repo) | Out-Null
        } '*expected ''v0.2.0''*'

        Assert-Equal $manifestBefore ([System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.toml'))) 'Failed version update must restore Cargo.toml.'
        Assert-Equal $lockBefore ([System.IO.File]::ReadAllBytes((Join-Path $repo 'Cargo.lock'))) 'Failed version update must restore Cargo.lock.'
    }
    finally {
        $env:GITHUB_REF_TYPE = $savedType
        $env:GITHUB_REF_NAME = $savedName
        $env:GITHUB_REF = $savedRef
        Remove-Item -LiteralPath $repo -Recurse -Force
    }
}

Invoke-TestCase 'release scripts expose help and reject malformed CLI input' {
    $checkHelp = Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--help')
    $setHelp = Invoke-ScriptCapture -ScriptPath $setVersionScript -Arguments @('--help')
    Assert-Contains $checkHelp 'Usage:' 'check-release help should show usage.'
    Assert-Contains $setHelp 'Usage:' 'set-version help should show usage.'

    Assert-Throws {
        Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--unknown') | Out-Null
    } 'Unknown option*'
    Assert-Throws {
        Invoke-ScriptCapture -ScriptPath $checkReleaseScript -Arguments @('--tag') | Out-Null
    } '*requires a value*'
    Assert-Throws {
        Invoke-ScriptCapture -ScriptPath $setVersionScript -Arguments @('--project', $projectRoot) | Out-Null
    } '*semantic version is required*'
    Assert-Throws {
        Invoke-ScriptCapture -ScriptPath $setVersionScript -Arguments @('1.02.3', '--project', $projectRoot) | Out-Null
    } '*not a valid semantic version*'
}

